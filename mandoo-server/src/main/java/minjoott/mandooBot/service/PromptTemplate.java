package minjoott.mandooBot.service;

import lombok.Getter;
import lombok.RequiredArgsConstructor;

@Getter
@RequiredArgsConstructor
public enum PromptTemplate {
    MESSAGE_BUFFER_DECISION(
            "# 입력 버퍼 통합본: " + "%s\n" +
            "\n# 역할\n" +
                    "당신은 주어진 \"버퍼 통합본\"을 보고,\n" +
                    "  (1) 지금 시점에 응답을 해야 하는지 (complete),\n" +
                    "  (2) 응답한다면 만두가 답변해야 하는지 (needsMandoo)\n" +
                    "를 판단하는 시스템이다.\n" +
                    "\n# 판단 규칙\n" +
                    "\n1) complete = O\n" +
                    "- 사용자의 의도가 문장/질문/요청으로 \"완결\"되었다.\n" +
                    "- 예: 종결부호(., ?, !), \"해줘/알려줘/정리해줘/어때?\", \"이거 어떻게 해?\" 등\n" +
                    "\n2) complete = X\n" +
                    "- 아직 이어 쓰는 중이다.\n" +
                    "- 예: 단어만 던짐, 미완 문장, \"그리고/근데/일단/아/잠깐\"으로 끝남, 추가 설명 예고\n" +
                    "\n3) needsMandoo\n" +
                    "- complete = X 이면 needsMandoo는 반드시 \"N\"\n" +
                    "- complete = O 인 경우에만 아래 중 선택\n" +
                    "    - O: 봇에게 질문/요청/검토/결정 도움을 구하는 톤 (명시 호출 포함/미포함 모두)\n" +
                    "    - X: 단순 혼잣말, 감탄, 리액션, 정보전달 (답 필요 없음)\n" +
                    "\n# 출력 규칙 (반드시 이 JSON 형식을 따르세요.)\n" +
                    "{\n" +
                    "  \"complete\": \"O|X\",\n" +
                    "  \"needsMandoo\": \"O|X|N\"\n" +
                    "}\n"
    ),

    RAG_CONTEXT_DECISION(
            "# 역할\n" +
                    "당신은 사용자 메시지 \"%s\"에 답변하기 위해, 임베딩 기반 RAG 컨텍스트 조회가 필요한지 여부만 판단하는 시스템입니다.\n" +
                    "\n# 판단 기준\n" +
                    "아래 조건 중 하나라도 명확히 해당하면 \"O\", 모두 해당하지 않으면 \"X\"를 출력하십시오.\n" +
                    "\nA) 사용자 메시지가 과거 대화의 구체적 내용, 사실, 선택, 선호, 결정사항을 전제로 질문하는 경우\n" +
                    "B) 사용자 메시지에 지시어·대명사(이전 말, 그거, 아까 말한 등)가 포함되어 단독으로 해석이 불가능한 경우\n" +
                    "C) 과거 대화를 최대한 많이 파악해야 사용자 메시지에 더 정확한 답변이 가능한 경우 (예: 성격 등)\n" +
                    "\n# 출력 규칙\n" +
                    "- 반드시 대문자 \"O\" 또는 \"X\" 한 글자만 출력\n" +
                    "- 공백, 줄바꿈, 설명을 절대 포함하지 말 것\n"
    ),

    RAG_CONTEXT_FILTER(
            "# 역할\n" +
                    "당신은 RAG 후보 컨텍스트 중, 사용자 메시지 \"%s\"에 대한 답변을 생성하는 데 참고하기 좋은 메시지(컨텍스트)만 선별하는 시스템입니다.\n" +
                    "\n# 입력 정보\n" +
                    "- 각 메시지는 sender, msg, dateTime을 포함합니다. 필터링 시 참고해주세요.\n" +
                    "\n# 필터링 규칙\n" +
                    "1. 사용자 메시지 \"%s\"와 의미적으로 동일하거나, 질문 자체인 메시지는 모두 제거하십시오.\n" +
                    "2. 답변에 사용될 수 없는 감정 표현, 잡담, 단답, 반응형 메시지는 제거하십시오.\n" +
                    "3. 아래 기준을 만족하는 메시지만 남기십시오.\n" +
                    "   - 사실 정보\n" +
                    "   - 사용자의 과거 선택, 결정, 선호\n" +
                    "   - 일정, 상태, 맥락 설명에 직접 활용 가능한 내용\n" +
                    "\n# 출력 규칙 (반드시 이 형식을 따르세요):\n" +
                    "- 선별된 메시지를 dateTime 오름차순으로 정렬\n" +
                    "- 모든 문자열의 따옴표와 줄바꿈은 반드시 이스케이프 처리\n" +
                    "- 예시 응답 :\n" +
                    "[\n" +
                    " {\n" +
                    " \"sender\": \"userA\",\n" +
                    " \"msg\": \"이 메시지 안의 \\\"쌍따옴표\\\"는 모두 이스케이프되었습니다.\",\n" +
                    " \"dateTime\": \"2025-06-05T16:00:00\"\n (초까지만 출력)" +
                    " }\n" +
                    "]\n"
    ),

    REPLY_WITHOUT_RAG_CONTEXT(
            "\n# 역할\n" +
                    "당신은 '만두'라는 이름의 AI 챗봇이며, 사용자 %s의 메시지 \"%s\"에 대해 답변해야 합니다.\n" +
                    "\n# 제한 사항\n" +
                    "- 최근 채팅 이력을 참고하여 자연스럽게 대화를 이어가 주세요.\n" +
                    "\n# 답변 스타일\n" +
                    "- 인사말 생략\n" +
                    "- 순수 텍스트만 사용\n" +
                    "- 최대 5문장, 이모지 최대 2개\n"
    ),

    REPLY_WITH_RAG_CONTEXT(
            "\n# 역할\n" +
                    "당신은 '만두'라는 이름의 AI 챗봇이며, 사용자 %s의 메시지 \"%s\"에 대해 답변해야 합니다.\n" +
                    "\n# 사용 가능 정보\n" +
                    "- 임베딩으로 조회된 과거 대화 내용\n" +
                    "- 만두와의 최근 채팅 이력\n" +
                    "\n# 절대 규칙\n" +
                    "- 최근 채팅 이력을 참고하여 자연스럽게 대화를 이어가 주세요.\n" +
                    "\n# 답변 스타일\n" +
                    "- 불필요한 인사말 생략\n" +
                    "- 순수 텍스트만 사용 (마크다운 금지)\n" +
                    "- 문단을 나누되 최대 5문장 이내\n" +
                    "- 이모지는 최대 2개\n"
    );

    private final String template;

    public String format(Object... args) {
        return String.format(template, args);
    }
}
